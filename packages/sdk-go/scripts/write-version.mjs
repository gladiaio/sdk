#!/usr/bin/env bun

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const __filename = fileURLToPath(import.meta.url)
const __dirname = dirname(__filename)

const projectRoot = resolve(__dirname, '..')
const versionPath = resolve(projectRoot, 'sdk.version')
const outDir = resolve(projectRoot, 'version')
const outPath = resolve(outDir, 'version.go')

const version = readFileSync(versionPath, 'utf8').trim()
if (!version) {
  console.error('[sdk-go] sdk.version file is empty')
  process.exit(1)
}

mkdirSync(outDir, { recursive: true })

const content = `// Code generated by write-version.mjs. DO NOT EDIT.

package version

const SDKVersion = ${JSON.stringify(version)}
`

writeFileSync(outPath, content, 'utf8')
console.log(`[sdk-go] Wrote ${outPath} with version ${version}`)
